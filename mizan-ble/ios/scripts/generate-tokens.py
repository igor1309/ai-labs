#!/usr/bin/env python3
"""Generate the Mizan design system's tokens in Swift from the design file's variables.

It reads mizan-ble/docs/design/tokens.json, the pencil MCP's `GetVariables()`
output for mizan-ble.pen. The design README says how to refresh it.

    python3 -I scripts/generate-tokens.py           # write the Swift file
    python3 -I scripts/generate-tokens.py --check   # exit 1 if it is stale

Only the design system's `mz-*` variables become tokens; the rest belong to
the explorations. Names drop the prefix and camel-case the kebab:
`mz-host-hi` is `hostHi`, `mz-space-12` is `space12`. The design system has
one appearance, so a themed `mz-*` variable is an error.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT.parent / "docs/design/tokens.json"
OUTPUT = ROOT / "Sources/DesignSystem/Tokens.swift"
PREFIX = "mz-"


def swift_name(token):
    head, *rest = token.removeprefix(PREFIX).split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def color(hex_value):
    digits = hex_value.lstrip("#")
    rgb, alpha = digits[:6], digits[6:] or "FF"
    return f"Color.hex(0x{rgb.upper()}, 0x{alpha.upper()})"


def declaration(name, token):
    kind, raw = token["type"], token["value"]
    if not isinstance(raw, (str, int, float)):
        sys.exit(f"{name} is themed; the design system has one appearance")
    if kind == "color":
        return f"public static let {swift_name(name)} = {color(raw)}"
    if kind == "string":
        return f"public static let {swift_name(name)} = {json.dumps(raw, ensure_ascii=False)}"
    return f"public static let {swift_name(name)}: CGFloat = {raw:g}"


def render(variables):
    tokens = {name: token for name, token in variables.items() if name.startswith(PREFIX)}
    cases = {"color": "color", "string": "string", "number": "number"}
    lines = [
        "// Generated by scripts/generate-tokens.py from docs/design/tokens.json.",
        "// Do not edit; change the design and regenerate.",
        "",
        "import SwiftUI",
        "",
        "/// The Mizan design system's tokens: the design file's `mz-*` variables,",
        "/// named without the prefix.",
        "public enum Tokens {",
        "",
    ]
    lines += [f"    {declaration(name, token)}" for name, token in tokens.items()]
    lines += [
        "}",
        "",
        "extension Tokens {",
        "",
        "    /// Every token under its name in the design file.",
        "    static let byName: [String: Token] = [",
    ]
    lines += [
        f'        "{name}": .{cases[token["type"]]}({swift_name(name)}),'
        for name, token in tokens.items()
    ]
    lines += ["    ]", "}", ""]
    return "\n".join(lines), len(tokens)


def main():
    variables = json.loads(SNAPSHOT.read_text())["variables"]
    swift, count = render(variables)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != swift:
            print(f"stale: {OUTPUT.relative_to(ROOT)}; run scripts/generate-tokens.py")
            sys.exit(1)
        print(f"ok: {count} tokens")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(swift)
    print(f"wrote {count} tokens to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
