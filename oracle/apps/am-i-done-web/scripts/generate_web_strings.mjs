import { readFile, writeFile, mkdir } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const currentDirectory = path.dirname(fileURLToPath(import.meta.url))
const webRootDirectory = path.resolve(currentDirectory, "..")

const stringsEnPath = path.join(webRootDirectory, "src/i18n/strings_en.json")
const stringsRuPath = path.join(webRootDirectory, "src/i18n/strings_ru.json")
const generatedDirectory = path.join(webRootDirectory, "src/generated")
const generatedPath = path.join(generatedDirectory, "strings.generated.js")

const stringsEn = await readJson(stringsEnPath)
const stringsRu = await readJson(stringsRuPath)

await mkdir(generatedDirectory, { recursive: true })

const generatedSource = [
  "// This file is generated by oracle/apps/am-i-done-web/scripts/generate_web_strings.mjs.",
  "// Do not edit manually.",
  "",
  "export const stringsByLocale = " + JSON.stringify({
    en: stringsEn,
    ru: stringsRu
  }, null, 2) + ";",
  ""
].join("\n")

await writeFile(generatedPath, generatedSource, "utf8")

async function readJson(filePath) {
  const raw = await readFile(filePath, "utf8")
  return JSON.parse(raw)
}

