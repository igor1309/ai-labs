#!/usr/bin/env node

/**
 * Generate release-units.toml from release-units.config.toml.
 *
 * Usage:
 *   node scripts/release/generate-manifest.js           # writes release-units.toml
 *   node scripts/release/generate-manifest.js --check   # exits non-zero if manifest drifts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { loadConfig, discoverUnits } from './lib/manifest.js';
import { stringify } from './lib/toml.js';

const rootIdx = process.argv.indexOf('--root');
const repoRoot = rootIdx !== -1
  ? resolve(process.argv[rootIdx + 1])
  : resolve(import.meta.dirname, '..', '..');
const manifestPath = join(repoRoot, 'release-units.toml');
const check = process.argv.includes('--check');

const config = loadConfig(repoRoot);
const units = discoverUnits(repoRoot, config.paths);

const manifest = stringify(
  { units },
  {
    header:
      'Auto-generated by scripts/release/generate-manifest.js — do not edit.\n' +
      'Re-generate: node scripts/release/generate-manifest.js',
  },
);

if (check) {
  let existing = '';
  try {
    existing = readFileSync(manifestPath, 'utf8');
  } catch {
    // file missing counts as drift
  }
  if (existing !== manifest) {
    process.stderr.write(
      'release-units.toml is out of date. Run: node scripts/release/generate-manifest.js\n',
    );
    process.exit(1);
  }
  process.stdout.write('release-units.toml is up to date.\n');
} else {
  writeFileSync(manifestPath, manifest, 'utf8');
  process.stdout.write(`Wrote ${manifestPath}\n`);
}
