#!/usr/bin/env python3
"""Generate the Glass Ledger tokens in Swift from the design file's variables.

It reads audelin/docs/design/tokens.json, the pencil MCP's `GetVariables()`
output for visual-language.pen. The design README says how to refresh it.

    python3 -I scripts/generate-tokens.py           # write the Swift file
    python3 -I scripts/generate-tokens.py --check   # exit 1 if it is stale

Token names become Swift names by camel-casing the kebab: `radius-panel` is
`radiusPanel`, `space-12` is `space12`. Colours take a light and a dark value;
every other token is the same in both.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT.parent / "docs/design/tokens.json"
OUTPUT = ROOT / "Sources/GlassLedger/GlassLedger+Tokens.swift"
THEMES = ("light", "dark")


def swift_name(token):
    head, *rest = token.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def swift_type(kind):
    return {"color": "Color", "string": "String", "number": "CGFloat"}[kind]


def color(hex_value):
    digits = hex_value.lstrip("#")
    rgb, alpha = digits[:6], digits[6:] or "FF"
    return f".hex(0x{rgb.upper()}, 0x{alpha.upper()})"


def value(token, theme):
    kind, raw = token["type"], token["value"]
    if kind == "color":
        by_theme = {entry["theme"]["mode"]: entry["value"] for entry in raw}
        return color(by_theme[theme])
    if kind == "string":
        return json.dumps(raw, ensure_ascii=False)
    return f"{raw:g}"


def render(variables):
    lines = [
        "// Generated by scripts/generate-tokens.py from docs/design/tokens.json.",
        "// Do not edit; change the design and regenerate.",
        "",
        "import SwiftUI",
        "",
        "/// The Glass Ledger design system's tokens for one appearance, named as in",
        "/// the design file.",
        "public struct GlassLedger: Sendable {",
        "",
    ]
    for name, token in variables.items():
        lines.append(f"    public let {swift_name(name)}: {swift_type(token['type'])}")
    lines.append("")
    for theme in THEMES:
        lines.append(f"    public static let {theme} = GlassLedger(")
        args = [f"        {swift_name(name)}: {value(token, theme)}" for name, token in variables.items()]
        lines.append(",\n".join(args))
        lines += ["    )", ""]
    lines[-1:] = ["}", ""]
    return "\n".join(lines)


def main():
    variables = json.loads(SNAPSHOT.read_text())["variables"]
    swift = render(variables)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != swift:
            print(f"stale: {OUTPUT.relative_to(ROOT)}; run scripts/generate-tokens.py")
            sys.exit(1)
        print(f"ok: {len(variables)} tokens")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(swift)
    print(f"wrote {len(variables)} tokens to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
