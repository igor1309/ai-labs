// Package folderindex generates a Markdown index from local repository READMEs.
package folderindex

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"path/filepath"
	"slices"
	"strings"
)

const command = "audelin-folder-index"

// Run writes the folder index and returns the command's exit code. home is
// the user's home folder: the settings and the default index live under
// home/.audelin/feed.
func Run(args []string, home string, stderr io.Writer) int {
	flags := flag.NewFlagSet(command, flag.ContinueOnError)
	flags.SetOutput(stderr)
	feed := filepath.Join(home, ".audelin", "feed")
	settingsPath := flags.String("settings", filepath.Join(feed, "folder-index.json"), "settings file naming the roots")
	out := flags.String("out", filepath.Join(feed, "folders.md"), "destination Markdown file")
	flags.Usage = func() { fmt.Fprintf(stderr, "Usage: %s [-settings <file>] [-out <file>]\n", command) }
	if err := flags.Parse(args); err != nil {
		return 2
	}
	if home == "" || *out == "" || *settingsPath == "" || flags.NArg() != 0 {
		flags.Usage()
		return 2
	}
	destination, err := filepath.Abs(*out)
	if err == nil && insideClaudeSkills(destination) {
		err = errors.New("expected a path outside .claude/skills")
	}
	if err != nil {
		fmt.Fprintf(stderr, "index %q: %v\n", *out, err)
		return 1
	}

	disk := diskJob(*settingsPath, home, destination)
	if err := disk.generate(); err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	return 0
}

// job is one generation: the roots are loaded, their entries collected and
// the index published, each step only after the one before succeeded.
type job struct {
	load    func() ([]string, error)
	collect func(roots []string) (map[string]entry, error)
	publish func(index string) error
}

func (j job) generate() error {
	roots, err := j.load()
	if err != nil {
		return err
	}
	entries, err := j.collect(roots)
	if err != nil {
		return err
	}
	return j.publish(render(roots, entries))
}

func insideClaudeSkills(path string) bool {
	parts := strings.Split(filepath.Clean(path), string(filepath.Separator))
	for i := 0; i+1 < len(parts); i++ {
		if parts[i] == ".claude" && parts[i+1] == "skills" {
			return true
		}
	}
	return false
}

type entry struct {
	readme  string
	summary string
}

func render(roots []string, entries map[string]entry) string {
	var out strings.Builder
	out.WriteString("# Folder index\n\nGenerated by `" + command + "` from ")
	for i, root := range roots {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString(codePath(root))
	}
	out.WriteString(".\n\n")

	paths := make([]string, 0, len(entries))
	for path := range entries {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	linkPath := strings.NewReplacer("\\", `\\`, "<", `\<`, ">", `\>`, "\n", "%0A", "\r", "%0D")
	for _, path := range paths {
		item := entries[path]
		fmt.Fprintf(&out, "- %s: %s", codePath(path), item.summary)
		if item.readme != "" {
			fmt.Fprintf(&out, " ([README](<%s>))", linkPath.Replace(item.readme))
		}
		out.WriteByte('\n')
	}
	return out.String()
}

func codePath(path string) string {
	path = strings.ReplaceAll(strings.ReplaceAll(path, "\n", `\n`), "\r", `\r`)
	fence := "`"
	for strings.Contains(path, fence) {
		fence += "`"
	}
	if len(fence) > 1 {
		path = " " + path + " "
	}
	return fence + path + fence
}
